import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {execFileSync} from 'node:child_process';
import * as THREE from 'three';
const {transformSync}=await import('esbuild');
const code=transformSync(readFileSync(new URL('../src/muspelheimTerrain.ts',import.meta.url),'utf8'),{loader:'ts',format:'esm'}).code.replace("from \"three\"",`from ${JSON.stringify(import.meta.resolve('three'))}`);
const {createTerrainSampler,clampMuspelheimPosition}=await import('data:text/javascript;base64,'+Buffer.from(code).toString('base64'));
const p=new Float32Array([0,0,0,2,2,0,0,4,2,2,8,2]);
const geo=new THREE.BufferGeometry();geo.setAttribute('position',new THREE.BufferAttribute(p,3));
const mesh=new THREE.Mesh(geo);const sample=createTerrainSampler(mesh);
assert.equal(sample(.5,.5),1.5);assert.equal(sample(1.5,1.5),5.5);assert.equal(sample(2,2),8);assert.equal(sample(-1,0),null);
geo.attributes.position.setY(0,-4);assert.equal(sample(0,0),-4);
assert.deepEqual(clampMuspelheimPosition(200,-200),{x:147,z:-147});
const b=readFileSync(new URL('../public/img/models/Muspelheim_Terrain_300m.glb',import.meta.url));
assert.equal(b.readUInt32LE(0),0x46546c67);assert.equal(b.readUInt32LE(8),b.length);
const json=JSON.parse(b.subarray(20,20+b.readUInt32LE(12)).toString());
assert.equal(json.accessors[0].count,22801);assert.equal(json.accessors[3].count,135000);
const app=readFileSync(new URL('../src/App.tsx',import.meta.url),'utf8');
assert.match(app,/React.lazy\(\(\)=>loadWorld\('muspelheim'/);
assert.match(app,/canOpenGate=\{crystal.canOpenGate\}/);
console.log('Muspelheim: triangle heights, editable depressions, boundaries, GLB and lazy route passed');
