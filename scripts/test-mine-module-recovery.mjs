import assert from 'node:assert/strict';
import fs from 'node:fs';
import {buildSync} from 'esbuild';
const code=buildSync({entryPoints:['src/worldLoading.ts'],bundle:true,write:false,format:'esm',platform:'node'}).outputFiles[0].text;
const {loadWorld,consumeWorldRecovery}=await import('data:text/javascript;base64,'+Buffer.from(code).toString('base64'));
const saved=new Map([['yggdrasil:ash-mine-visit:v1','{"active":true,"hp":246}'],['save','player progress']]);
globalThis.sessionStorage={getItem:k=>saved.get(k)??null,setItem:(k,v)=>saved.set(k,v),removeItem:k=>saved.delete(k)};
const navigations=[];
globalThis.window={location:{href:'https://example.test/yggdrasil-tma/?tgWebAppStartParam=play#telegram',replace:url=>navigations.push(url)}};
const stale=new TypeError('Failed to fetch dynamically imported module: /assets/AshMine3D-old.js');
const fail=async()=>{throw stale;};
void loadWorld('muspelheim',fail,'ash-mine');
await new Promise(resolve=>setImmediate(resolve));
assert.equal(navigations.length,1,'Stale mine chunk reloads automatically');
assert.equal(consumeWorldRecovery(),'muspelheim','Reload returns directly to the correct world');
assert.ok(navigations[0].includes('worldVersion='));
assert.ok(navigations[0].includes('tgWebAppStartParam=play'));
assert.ok(navigations[0].endsWith('#telegram'));
await loadWorld('muspelheim',async()=>({default:'realm'}));
await assert.rejects(loadWorld('muspelheim',fail,'ash-mine'),error=>error===stale);
assert.equal(navigations.length,1,'Successful parent load does not reset the failed mine retry or create a reload loop');
assert.equal(saved.get('yggdrasil:ash-mine-visit:v1'),'{"active":true,"hp":246}','Mine checkpoint survives recovery');
assert.equal(saved.get('save'),'player progress');
await loadWorld('muspelheim',async()=>({default:'mine'}),'ash-mine');
assert.equal(saved.has('yggdrasil:world-retry:ash-mine'),false);
await assert.rejects(loadWorld('muspelheim',async()=>{throw new Error('Render bug');},'ash-mine'),/Render bug/);
const realm=fs.readFileSync('src/MuspelheimRealm.tsx','utf8');
assert.match(realm,/loadWorld\('muspelheim',\(\)=>import\('\.\/AshMine3D'\),'ash-mine'\)/);
console.log('Mine module recovery: automatic refresh, direct return, checkpoint preservation and reload-loop protection passed.');
